defmodule Gumbo.Patches do
  @moduledoc """
  Regenerates the vendored-parser patch series.

  Each `.patch` under `c_src/patches/gumbo-parser/` is the build's input: the
  Makefile copies the pinned source and applies every patch to it, in order. The
  patches are therefore both the build's input and the record of what each change is,
  and a generator exists for the ones that are mechanical: it applies the earlier
  patches, performs a list of literal substitutions, and writes the patch back out as
  the diff of the pinned source against the result.

  That is what `mix gumbo.patches` does. The substitutions live next to the patch, in
  a `.exs` of the same name, and each one asserts how many occurrences it must find:
  that assertion is the rebase tool, because a pin bump that moves the code fails here
  — naming the file and the snippet — instead of producing a patch that applies with a
  different meaning.

  The diff itself is `Gumbo.Patches.Diff`, a port of Python's `difflib`, so that a
  regenerated patch is byte-identical to the one the Python generators produced.
  `mix gumbo.patches --check` asserts exactly that, and `make check-generators` runs
  it in `mix ci`.
  """

  alias Gumbo.Patches.Diff

  @patch_dir "c_src/patches/gumbo-parser"
  @pin_dir "c_src/gumbo-parser/src"
  @scratch "priv/obj/patches-regen"

  @type definition :: %{
          required(:priors) => boolean(),
          required(:header) => binary(),
          required(:subs) => [sub()]
        }
  @type sub :: %{
          required(:file) => binary(),
          required(:count) => pos_integer(),
          required(:from) => binary(),
          required(:to) => binary()
        }

  @doc "Every definition, sorted by patch name, as `{name, definition}`."
  @spec definitions(binary()) :: [{binary(), definition()}]
  def definitions(root \\ File.cwd!()) do
    root
    |> Path.join(@patch_dir)
    |> Path.join("*.exs")
    |> Path.wildcard()
    |> Enum.sort()
    |> Enum.map(fn path -> {Path.basename(path, ".exs"), load(path)} end)
  end

  @doc "The committed patch names, sorted, definitions or not."
  @spec patches(binary()) :: [binary()]
  def patches(root \\ File.cwd!()) do
    root
    |> Path.join(@patch_dir)
    |> Path.join("*.patch")
    |> Path.wildcard()
    |> Enum.map(&Path.basename(&1, ".patch"))
    |> Enum.sort()
  end

  @doc """
  Regenerates one patch and compares it with the committed file.

  Returns `:ok`, or `{:changed, generated}` when the bytes differ, or
  `{:missing, generated}` when there is no committed file to compare with.
  """
  @spec check(binary(), binary()) :: :ok | {:changed, binary()} | {:missing, binary()}
  def check(name, root \\ File.cwd!()) do
    generated = generate(name, root)
    path = Path.join([root, @patch_dir, name <> ".patch"])

    case File.read(path) do
      {:ok, ^generated} -> :ok
      {:ok, _other} -> {:changed, generated}
      {:error, :enoent} -> {:missing, generated}
    end
  end

  @doc """
  Regenerates `name` and writes it, returning `:created` when there was no file to
  compare against, `:written` when there was one and it differed, and `:unchanged`
  when it already says what the definition produces.

  `:created` is what makes a new patch a one-step thing: a definition with no committed
  `.patch` next to it used to have no way through here, and the placeholder that stood in
  for one was a file the build tried to apply.
  """
  @spec write(binary(), binary()) :: :created | :written | :unchanged
  def write(name, root \\ File.cwd!()) do
    generated = generate(name, root)
    path = Path.join([root, @patch_dir, name <> ".patch"])

    case File.read(path) do
      {:error, :enoent} ->
        File.write!(path, generated)
        :created

      {:ok, ^generated} ->
        :unchanged

      _ ->
        File.write!(path, generated)
        :written
    end
  end

  @doc """
  The generated bytes of patch `name`: the pinned source with the earlier patches
  applied, this patch's substitutions run in order, and the diff as `difflib` renders
  it, preceded by the definition's header.
  """
  @spec generate(binary(), binary()) :: binary()
  def generate(name, root \\ File.cwd!()) do
    definition = load(Path.join([root, @patch_dir, name <> ".exs"]))
    scratch = Path.join(root, @scratch)
    relative = Path.relative_to(scratch, root)

    prepare(scratch, root, name, relative, definition)

    files = touched(definition)
    read = fn file -> File.read!(Path.join([scratch, "src", file])) end
    base = Map.new(files, &{&1, read.(&1)})

    Enum.each(definition.subs, &substitute(&1, scratch, name))
    after_text = Map.new(files, &{&1, read.(&1)})

    body =
      files
      |> Enum.map(fn file ->
        Diff.unified(
          Diff.splitlines(base[file]),
          Diff.splitlines(after_text[file]),
          "a/src/#{file}",
          "b/src/#{file}"
        )
      end)
      |> IO.iodata_to_binary()

    body = if body == "" or String.ends_with?(body, "\n"), do: body, else: body <> "\n"
    definition.header <> body
  end

  defp prepare(scratch, root, name, relative, definition) do
    File.rm_rf!(scratch)
    File.mkdir_p!(scratch)
    File.cp_r!(Path.join(root, @pin_dir), Path.join(scratch, "src"))

    if definition.priors do
      apply_priors(root, name, relative)
    end
  end

  defp apply_priors(root, name, relative) do
    number = String.slice(name, 0, 4)

    root
    |> Path.join(@patch_dir)
    |> Path.join("*.patch")
    |> Path.wildcard()
    |> Enum.filter(&(String.slice(Path.basename(&1), 0, 4) < number))
    |> Enum.sort()
    |> Enum.each(fn patch ->
      case System.cmd("git", ["apply", "-p1", "--directory=#{relative}", patch],
             cd: root,
             stderr_to_stdout: true
           ) do
        {_out, 0} ->
          :ok

        {out, status} ->
          raise """
          #{Path.basename(patch)} does not apply to the pinned source (git apply exited #{status}):

          #{out}
          """
      end
    end)
  end

  defp substitute(sub, scratch, name) do
    path = Path.join([scratch, "src", sub.file])
    text = File.read!(path)

    guard_terminators!(text, sub.file, name)

    found = count(text, sub.from)

    if found != sub.count do
      raise """
      #{name}: expected #{sub.count} occurrence(s) of a substitution in #{sub.file}, found #{found}.

      In #{sub.file}:
      #{first_line(sub.from)}

      Either the pin moved and this substitution needs a rebase, or the definition is wrong.
      """
    end

    File.write!(path, String.replace(text, sub.from, sub.to))
  end

  defp guard_terminators!(text, file, name) do
    if String.contains?(text, [
         "\v",
         "\f",
         "\x1c",
         "\x1d",
         "\x1e",
         "\x85",
         "\u2028",
         "\u2029",
         "\r"
       ]) do
      raise """
      #{name}: #{file} contains a line terminator Python's splitlines() would honour and
      Gumbo.Patches.Diff.splitlines/1 does not. Refusing to generate a diff that would
      differ from the Python generators'.
      """
    end
  end

  defp count(text, from), do: length(:binary.matches(text, from))

  defp touched(definition),
    do: definition.subs |> Enum.map(& &1.file) |> Enum.uniq() |> Enum.sort()

  defp first_line(text), do: text |> String.split("\n", parts: 2) |> hd() |> String.slice(0, 100)

  defp load(path) do
    {definition, _} = Code.eval_file(path)
    definition
  end
end
