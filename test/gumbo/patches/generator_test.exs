defmodule Gumbo.Patches.GeneratorTest do
  use ExUnit.Case, async: true

  alias Gumbo.Patches

  import Gumbo.Test.Fixtures

  @repo_root Path.expand("../../..", __DIR__)

  test "every committed patch is what its definition produces" do
    for {name, _} <- Patches.definitions(@repo_root) do
      assert Patches.check(name, @repo_root) == :ok
    end
  end

  test "definitions and patches are sorted and disjoint in the documented way" do
    defined = Patches.definitions(@repo_root) |> Enum.map(&elem(&1, 0))
    all = Patches.patches(@repo_root)

    assert defined == Enum.sort(defined)
    assert all == Enum.sort(all)
    assert length(all) > length(defined), "the hand-written patch is the point of `patches/1`"
    assert Enum.all?(defined, &(&1 in all))
  end

  test "check/2 reports :changed when the committed bytes differ" do
    root = fake_root(%{patch: "not the generated bytes\n"})
    assert {:changed, generated} = Patches.check("0001-fixture", root)
    assert generated == Patches.generate("0001-fixture", root)
  end

  test "check/2 reports :missing when there is no committed patch" do
    root = fake_root(%{patch: nil})
    assert {:missing, _generated} = Patches.check("0001-fixture", root)
  end

  test "write/2 writes only when the bytes differ, and then writes exactly those bytes" do
    stale = fake_root(%{patch: "stale\n"})
    assert Patches.write("0001-fixture", stale) == :written

    assert File.read!(Path.join(stale, "c_src/patches/gumbo-parser/0001-fixture.patch")) ==
             Patches.generate("0001-fixture", stale)

    fresh = fake_root(%{patch: :generated})
    assert Patches.write("0001-fixture", fresh) == :unchanged
  end

  test "a substitution that finds the wrong number of occurrences refuses to generate" do
    root = fake_root(%{count: 7})
    message = assert_raise RuntimeError, fn -> Patches.generate("0001-fixture", root) end
    assert message.message =~ "expected 7 occurrence(s)"
    assert message.message =~ "0001-fixture: expected"
  end

  test "a source file carrying a terminator Python would split on refuses to generate" do
    root = fake_root(%{file_body: "alpha\rbeta\n"})
    message = assert_raise RuntimeError, fn -> Patches.generate("0001-fixture", root) end
    assert message.message =~ "splitlines() would honour"
  end
end
